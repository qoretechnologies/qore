"""Regenerates cmake/scu-chunk-costs.txt (the cost table behind SINGLE_COMPILATION_UNIT_CHUNKS, see
cmake/QoreScuChunks.cmake) from per-file compile timings.

usage: tools/update-scu-chunk-costs.py <timing log> [<output file>]

The timing log has one line per compiled file, "<wall seconds> <max RSS kB> <source path>", as written by a compiler
launcher that wraps the compiler in "/usr/bin/time -f '%e %M'" (CMAKE_CXX_COMPILER_LAUNCHER) in a
SINGLE_COMPILATION_UNIT=OFF RelWithDebInfo build of libqore.  Costs are rounded to 10 ms; only .cpp files, by base name,
are kept, which covers the lib sources and the generated parser, scanner and qpp sources.
"""
import os
import sys


def main(argv):
    if len(argv) < 2 or len(argv) > 3:
        print(__doc__, file=sys.stderr)
        return 2
    costs = {}
    with open(argv[1], encoding="utf-8") as f:
        for line in f:
            parts = line.split(None, 2)
            if len(parts) != 3:
                continue
            try:
                ms = int(round(float(parts[0]) * 100.0)) * 10
            except ValueError:
                continue
            name = os.path.basename(parts[2].strip())
            if not name.endswith(".cpp"):
                continue
            costs[name] = max(costs.get(name, 0), ms)
    out = argv[2] if len(argv) == 3 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "cmake",
                                                      "scu-chunk-costs.txt")
    with open(out, "w", encoding="utf-8") as f:
        f.write("# Copyright 2026 Qore Technologies, s.r.o.\n")
        f.write("# Per-file compile cost (ms) for the libqore unity chunk assignment (cmake/QoreScuChunks.cmake).\n")
        f.write("# Generated by tools/update-scu-chunk-costs.py; format: <cost> <file name>\n")
        for name in sorted(costs):
            f.write("%d %s\n" % (costs[name], name))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
