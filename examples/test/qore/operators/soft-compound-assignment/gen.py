#!/usr/bin/env python3
# generates the fixture SoftCompoundAssignment.q: each compound operation on each soft lvalue (a local variable, a
# class member, a hashdecl member), printing the value of the expression and the value of the lvalue afterwards
import sys

cases = [
    ("softstring", '"6"', ["*= 2", "-= 1", "+= 1", "/= 4", "/= 4.0", "*= 1.5", "*= 2n", "%= 4", "|= 1", "&= 3",
        "^= 3", "<<= 1", ">>= 1", "++", "--", "pre++", "pre--"]),
    ("softbool", "True", ["*= 2", "-= 1", "+= 1", "/= 2", "*= 1.5", "%= 1", "|= 0", "&= 0", "^= 1", "<<= 1",
        ">>= 1", "++", "--", "pre++", "pre--"]),
    ("*softstring", '"6"', ["*= 2", "-= 1", "|= 1", "++"]),
    ("softint", "6", ["*= 1.5", "/= 4.0", "*= 2n", "-= 1.5", "+= 1.5"]),
    ("softfloat", "6.0", ["|= 1", "%= 4", "*= 2n", "-= 1", "-= 2n"]),
    ("softnumber", "6n", ["|= 1", "%= 4", "<<= 1", "-= 1.5", "-= 1"]),
]

def expr(lv, op):
    if op == "++" or op == "--":
        return lv + op
    if op.startswith("pre"):
        return op[3:] + lv
    return "(%s %s)" % (lv, op)

out = []
out.append("""#!/usr/bin/env qore
# -*- mode: qore; indent-tabs-mode: nil -*-
# Copyright (C) 2026 Qore Technologies, s.r.o.

# Compound assignments and increments of soft-typed lvalues (softstring, softbool, *softstring, and softint,
# softfloat and softnumber with results of another type) are accepted at parse time when the lvalue's type converts
# the value that the operator assigns, as an assignment of that value is (qore#6304), and give the value and leave
# the lvalue as the AST interpreter does, in every execution mode: each operation on a local variable, a class member
# and a hashdecl member prints the value of the expression and the value of the lvalue afterwards, with their types.
# Generated by gen.py in the scratch directory of the change; the cases are listed in it.

%modern

sub show(string label, auto v, auto lv) {
    printf("%-34s %y (%s) -> %y (%s)\\n", label, v, v.type(), lv, lv.type());
}
""")
n = 0
for (t, init, ops) in cases:
    for op in ops:
        n += 1
        cls = "C%d" % n
        hd = "H%d" % n
        out.append("class %s { public { %s m = %s; } }" % (cls, t, init))
        out.append("hashdecl %s { %s m = %s; }" % (hd, t, init))
        out.append("sub t%d() {" % n)
        out.append("    { %s v = %s; auto r = %s; show(\"local %s %s\", r, v); }" % (t, init, expr("v", op), t, op))
        out.append("    { %s o(); auto r = %s; show(\"member %s %s\", r, o.m); }" % (cls, expr("o.m", op), t, op))
        out.append("    { hash<%s> h(); auto r = %s; show(\"hashdecl %s %s\", r, h.m); }" % (hd, expr("h.m", op),
            t, op))
        out.append("}")
calls = "\n".join("t%d();" % i for i in range(1, n + 1))
out.append(calls)
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print(n, "cases")
