"""Generates cases.q: for each case operator, case value and switch value type, a function with a switch case and one
with the equivalent if statement (qore#6252); the script compares their results for values of many types.

usage: python3 -I gen-cases.py > cases.q
"""

OPS = [("gt", ">"), ("ge", ">="), ("lt", "<"), ("le", "<="), ("eq", "==")]
CONSTS = [("i1", "1"), ("i0", "0"), ("f15", "1.5"), ("n2", "2n"), ("s1", '"1"'), ("sabc", '"abc"'), ("t", "True"),
          ("d", "2026-01-01")]
TYPES = [("auto", "auto"), ("int", "int"), ("float", "float"), ("bool", "bool"), ("string", "string"),
         ("buf", "*buffer<int64>")]
VALUES = {
    "auto": ["0", "1", "2", "-1", "1.5", "2.5n", '"1"', '"2"', '"abc"', '""', "True", "False", "NOTHING", "NULL",
             "2026-06-01", "2025-01-01", "new buffer<int64>((1, 2, 3))", "new buffer<int64>((0, 0, 0))",
             "new buffer<int64>()", "<0102>", "(1, 2)", '{"a": 1}'],
    "int": ["0", "1", "2", "-1"],
    "float": ["0.0", "1.0", "1.5", "2.5"],
    "bool": ["True", "False"],
    "string": ['""', '"0"', '"1"', '"2"', '"abc"'],
    "buf": ["new buffer<int64>((1, 2, 3))", "new buffer<int64>((0, 0, 0))", "new buffer<int64>()", "NOTHING"],
}


def main():
    out = ['''#!/usr/bin/env qore
# -*- mode: qore; indent-tabs-mode: nil -*-
# Copyright (C) 2026 Qore Technologies, s.r.o.

# qore#6252: a switch case with an operator (case OP x:) matches when value OP x is true as the condition of an if
# statement, in every execution mode; generated pairs of functions compare each case with the if statement
# (generated by gen-cases.py; do not edit)

%modern

hashdecl CaseResult {
    string label;
    string sw;
    string cond;
}
''']
    fns = []
    for tn, tt in TYPES:
        for on, o in OPS:
            for cn, c in CONSTS:
                name = f"{tn}_{on}_{cn}"
                out.append(f'''string sub sw_{name}({tt} v) {{
    switch (v) {{
        case {o} {c}: return "1";
    }}
    return "0";
}}
string sub if_{name}({tt} v) {{
    if (v {o} {c}) {{
        return "1";
    }}
    return "0";
}}
''')
                fns.append((tn, name, f"{o} {c}".replace('"', "'")))
    out.append('''# returns the result of a call, or the error of its exception
string sub res(code c, auto v) {
    try {
        return c(v);
    } catch (hash<ExceptionInfo> ex) {
        return "ex:" + ex.err;
    }
}
''')
    out.append("int sub main() {\n    int mismatches = 0;")
    for tn, _ in TYPES:
        out.append(f'    list<auto> {tn}_vals = ({", ".join(VALUES[tn])},);')
    for tn, name, label in fns:
        out.append(f'''    foreach auto v in ({tn}_vals) {{
        string s = res(\\sw_{name}(), v);
        string i = res(\\if_{name}(), v);
        printf("{tn}[%d] {label}: %s %s\\n", $#, s, i);
        if (s != i) {{
            ++mismatches;
        }}
    }}''')
    out.append('''    printf("mismatches: %d\\n", mismatches);
    return mismatches;
}

main();
''')
    print("\n".join(out), end="")


if __name__ == "__main__":
    main()
