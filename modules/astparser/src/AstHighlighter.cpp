// the text of queries/highlights.scm, generated by cmake/EmbedHighlightQuery.cmake
#include "astparser_highlight_query.h"

// The tree-sitter Qore language function, defined in the generated parser.c
extern "C" const TSLanguage* tree_sitter_qore();

namespace {
std::once_flag highlighterOnce;
AstHighlighter* highlighter = nullptr;
std::string highlighterError;

// Owns a tree-sitter query cursor
class QueryCursorHolder {
public:
    QueryCursorHolder() : cursor(ts_query_cursor_new()) {
    }

    ~QueryCursorHolder() {
        ts_query_cursor_delete(cursor);
    }

    QueryCursorHolder(const QueryCursorHolder&) = delete;
    QueryCursorHolder& operator=(const QueryCursorHolder&) = delete;

    TSQueryCursor* get() const {
        return cursor;
    }

private:
    TSQueryCursor* cursor;
};

// A capture of a match that satisfies its predicates
struct CaptureEntry {
    uint32_t start;
    uint32_t end;
    uint32_t pattern;
    uint32_t capture;
};

// Returns the line and column (1-based) of a byte offset in the text
void get_line_col(const char* text, uint32_t len, uint32_t offset, unsigned& line, unsigned& col) {
    line = 1;
    col = 1;
    for (uint32_t i = 0; i < offset && i < len; ++i) {
        if (text[i] == '\n') {
            ++line;
            col = 1;
        } else {
            ++col;
        }
    }
}

const char* get_query_error_name(TSQueryError error) {
    switch (error) {
        case TSQueryErrorSyntax: return "syntax error";
        case TSQueryErrorNodeType: return "unknown node type";
        case TSQueryErrorField: return "unknown field";
        case TSQueryErrorCapture: return "unknown capture";
        case TSQueryErrorStructure: return "impossible pattern structure";
        case TSQueryErrorLanguage: return "incompatible language";
        default: return "error";
    }
}
}

const AstHighlighter* AstHighlighter::get(std::string& err) {
    std::call_once(highlighterOnce, []() {
        try {
            std::unique_ptr<AstHighlighter> h(new AstHighlighter);
            if (h->init(highlighterError)) {
                highlighter = h.release();
            }
        } catch (const std::exception& e) {
            highlighterError = std::string("cannot compile the highlight query: ") + e.what();
        }
    });
    if (!highlighter) {
        err = highlighterError;
    }
    return highlighter;
}

void AstHighlighter::cleanup() {
    delete highlighter;
    highlighter = nullptr;
}

AstHighlighter::~AstHighlighter() {
    if (query) {
        ts_query_delete(query);
    }
}

bool AstHighlighter::init(std::string& err) {
    uint32_t errorOffset = 0;
    TSQueryError errorType = TSQueryErrorNone;
    uint32_t len = static_cast<uint32_t>(sizeof(astparser_highlight_query) - 1);
    query = ts_query_new(tree_sitter_qore(), astparser_highlight_query, len, &errorOffset, &errorType);
    if (!query) {
        unsigned line, col;
        get_line_col(astparser_highlight_query, len, errorOffset, line, col);
        err = std::string("cannot compile the highlight query (queries/highlights.scm): ")
            + get_query_error_name(errorType) + " at line " + std::to_string(line) + ", column "
            + std::to_string(col);
        return false;
    }

    uint32_t captureCount = ts_query_capture_count(query);
    captureNames.reserve(captureCount);
    for (uint32_t i = 0; i < captureCount; ++i) {
        uint32_t nameLen;
        const char* name = ts_query_capture_name_for_id(query, i, &nameLen);
        captureNames.emplace_back(name, nameLen);
    }

    uint32_t patternCount = ts_query_pattern_count(query);
    patternPredicates.resize(patternCount);
    for (uint32_t i = 0; i < patternCount; ++i) {
        if (!initPredicates(i, err)) {
            return false;
        }
    }
    return true;
}

bool AstHighlighter::initPredicates(uint32_t pattern, std::string& err) {
    uint32_t stepCount;
    const TSQueryPredicateStep* steps = ts_query_predicates_for_pattern(query, pattern, &stepCount);
    uint32_t i = 0;
    while (i < stepCount) {
        // a predicate is a list of steps that ends with TSQueryPredicateStepTypeDone and starts with its name
        uint32_t end = i;
        while (end < stepCount && steps[end].type != TSQueryPredicateStepTypeDone) {
            ++end;
        }
        auto stringValue = [&](uint32_t step) -> std::string {
            uint32_t valueLen;
            const char* value = ts_query_string_value_for_id(query, steps[step].value_id, &valueLen);
            return std::string(value, valueLen);
        };
        uint32_t byteOffset = ts_query_start_byte_for_pattern(query, pattern);
        auto fail = [&](const std::string& msg) {
            unsigned line, col;
            get_line_col(astparser_highlight_query, static_cast<uint32_t>(sizeof(astparser_highlight_query) - 1),
                byteOffset, line, col);
            err = "unsupported predicate in the highlight query (queries/highlights.scm) in the pattern at line "
                + std::to_string(line) + ": " + msg;
            return false;
        };
        if (end == i || steps[i].type != TSQueryPredicateStepTypeString) {
            return fail("a predicate has no name");
        }
        std::string name = stringValue(i);
        Predicate pred;
        pred.negated = !name.compare(0, 4, "not-");
        std::string base = pred.negated ? name.substr(4) : name;
        if (base == "eq?") {
            pred.kind = PredicateKind::Eq;
        } else if (base == "any-of?") {
            pred.kind = PredicateKind::AnyOf;
        } else if (base == "match?") {
            pred.kind = PredicateKind::Match;
        } else {
            return fail("#" + name);
        }
        uint32_t argCount = end - i - 1;
        if (argCount < 2 || steps[i + 1].type != TSQueryPredicateStepTypeCapture) {
            return fail("#" + name + " requires a capture and a value");
        }
        pred.capture = steps[i + 1].value_id;
        if (pred.kind == PredicateKind::Eq || pred.kind == PredicateKind::Match) {
            if (argCount != 2) {
                return fail("#" + name + " requires exactly two arguments");
            }
            if (steps[i + 2].type == TSQueryPredicateStepTypeCapture) {
                if (pred.kind == PredicateKind::Match) {
                    return fail("#" + name + " requires a regular expression");
                }
                pred.otherIsCapture = true;
                pred.otherCapture = steps[i + 2].value_id;
            } else if (pred.kind == PredicateKind::Eq) {
                pred.values.push_back(stringValue(i + 2));
            } else {
                try {
                    pred.regex = std::make_shared<std::regex>(stringValue(i + 2), std::regex::ECMAScript);
                } catch (const std::regex_error& e) {
                    return fail("#" + name + ": invalid regular expression: " + e.what());
                }
            }
        } else {
            for (uint32_t j = i + 2; j < end; ++j) {
                if (steps[j].type != TSQueryPredicateStepTypeString) {
                    return fail("#" + name + " requires strings");
                }
                pred.values.push_back(stringValue(j));
            }
        }
        patternPredicates[pattern].push_back(std::move(pred));
        i = end + 1;
    }
    return true;
}

bool AstHighlighter::matchesPredicates(const TSQueryMatch& match, const std::string& source) const {
    const std::vector<Predicate>& preds = patternPredicates[match.pattern_index];
    if (preds.empty()) {
        return true;
    }
    auto nodeText = [&](TSNode node) -> std::string {
        uint32_t start = ts_node_start_byte(node);
        uint32_t end = ts_node_end_byte(node);
        if (start > end || end > source.size()) {
            return std::string();
        }
        return source.substr(start, end - start);
    };
    // the text of the first capture with the given index in the match; a quantified capture is tested for each node
    auto firstText = [&](uint32_t capture, bool& found) -> std::string {
        for (uint16_t i = 0; i < match.capture_count; ++i) {
            if (match.captures[i].index == capture) {
                found = true;
                return nodeText(match.captures[i].node);
            }
        }
        found = false;
        return std::string();
    };
    for (const Predicate& pred : preds) {
        for (uint16_t i = 0; i < match.capture_count; ++i) {
            if (match.captures[i].index != pred.capture) {
                continue;
            }
            std::string text = nodeText(match.captures[i].node);
            bool result;
            switch (pred.kind) {
                case PredicateKind::Eq:
                    if (pred.otherIsCapture) {
                        bool found;
                        std::string other = firstText(pred.otherCapture, found);
                        result = found && text == other;
                    } else {
                        result = text == pred.values[0];
                    }
                    break;
                case PredicateKind::AnyOf:
                    result = std::find(pred.values.begin(), pred.values.end(), text) != pred.values.end();
                    break;
                case PredicateKind::Match:
                    result = std::regex_search(text, *pred.regex);
                    break;
                default:
                    result = false;
                    break;
            }
            if (result == pred.negated) {
                return false;
            }
        }
    }
    return true;
}

bool AstHighlighter::highlight(const AstParseResult& result, CSTCancelCheck& cancel,
        std::vector<AstHighlightSpan>& spans) const {
    const std::string& source = result.getSource();
    QueryCursorHolder cursor;
    ts_query_cursor_exec(cursor.get(), query, result.getRootNode());

    std::vector<CaptureEntry> entries;
    TSQueryMatch match;
    while (ts_query_cursor_next_match(cursor.get(), &match)) {
        if (cancel()) {
            return false;
        }
        if (!matchesPredicates(match, source)) {
            continue;
        }
        for (uint16_t i = 0; i < match.capture_count; ++i) {
            const TSQueryCapture& c = match.captures[i];
            uint32_t start = ts_node_start_byte(c.node);
            uint32_t end = std::min(ts_node_end_byte(c.node), static_cast<uint32_t>(source.size()));
            if (start < end) {
                entries.push_back({start, end, match.pattern_index, c.index});
            }
        }
    }

    // nodes nest, so sorting by start and then by decreasing end paints each node before the nodes inside it; for
    // the same range, the lowest pattern index is painted last and so wins
    std::sort(entries.begin(), entries.end(), [](const CaptureEntry& a, const CaptureEntry& b) {
        if (a.start != b.start) {
            return a.start < b.start;
        }
        if (a.end != b.end) {
            return a.end > b.end;
        }
        return a.pattern > b.pattern;
    });

    std::vector<int32_t> paint(source.size(), -1);
    for (const CaptureEntry& e : entries) {
        if (cancel()) {
            return false;
        }
        std::fill(paint.begin() + e.start, paint.begin() + e.end, static_cast<int32_t>(e.capture));
    }

    spans.clear();
    for (uint32_t i = 0, size = static_cast<uint32_t>(paint.size()); i < size;) {
        if (cancel()) {
            return false;
        }
        int32_t capture = paint[i];
        uint32_t j = i + 1;
        while (j < size && paint[j] == capture) {
            ++j;
        }
        if (capture >= 0) {
            spans.push_back({i, j, static_cast<uint32_t>(capture)});
        }
        i = j;
    }
    return true;
}

bool AstHighlighter::getErrors(const AstParseResult& result, CSTCancelCheck& cancel,
        std::vector<AstErrorSpan>& spans) {
    spans.clear();
    TSNode root = result.getRootNode();
    if (!ts_node_has_error(root)) {
        return true;
    }
    uint32_t size = static_cast<uint32_t>(result.getSource().size());
    return cst_walk(root, cancel, [&](const TSTreeCursor*, TSNode node, uint32_t) {
        if (ts_node_is_missing(node)) {
            uint32_t pos = std::min(ts_node_start_byte(node), size);
            spans.push_back({pos, pos, true});
            return CSTWalkAction::Skip;
        }
        if (ts_node_is_error(node)) {
            spans.push_back({std::min(ts_node_start_byte(node), size), std::min(ts_node_end_byte(node), size),
                false});
            return CSTWalkAction::Skip;
        }
        return ts_node_has_error(node) ? CSTWalkAction::Descend : CSTWalkAction::Skip;
    });
}

bool AstHighlighter::toCharOffsets(const std::string& source, std::vector<uint32_t*>& byteOffsets,
        CSTCancelCheck& cancel) {
    uint32_t chars = 0;
    uint32_t pos = 0;
    for (uint32_t* offset : byteOffsets) {
        if (cancel()) {
            return false;
        }
        uint32_t target = std::min(*offset, static_cast<uint32_t>(source.size()));
        for (; pos < target; ++pos) {
            if (!(pos % 4096) && cancel()) {
                return false;
            }
            // count the bytes that are not UTF-8 continuation bytes
            if ((static_cast<unsigned char>(source[pos]) & 0xC0) != 0x80) {
                ++chars;
            }
        }
        *offset = chars;
    }
    return true;
}
