// the namespace name must be the full path from the root namespace; see
// design/qore-module-structure.md
QoreNamespace AvroNs("Qore::Avro");

const TypedHashDecl* hashdeclAvroFieldInfo = nullptr;

static void avro_module_init(QoreModuleInitContext& ctx, ExceptionSink& xsink) {
    // AvroFieldInfo has an AvroSchema member, so the class must be registered first
    AvroNs.addSystemClass(initAvroSchemaClass(AvroNs));
    hashdeclAvroFieldInfo = init_hashdecl_AvroFieldInfo(AvroNs);
    AvroNs.addSystemClass(initAvroFileReaderClass(AvroNs));
    AvroNs.addSystemClass(initAvroFileWriterClass(AvroNs));
    init_avro_constants(AvroNs);
}

static void avro_module_ns_init(QoreNamespace* rns, QoreNamespace* qns, ExceptionSink& xsink) {
    qns->addNamespace(AvroNs.copy());
}

